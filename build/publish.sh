#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."
dotnet_bin="$(command -v dotnet || true)"
if [[ -z "$dotnet_bin" ]]; then
  dotnet_bin="$HOME/.dotnet/dotnet"
fi
test -x "$dotnet_bin" || { echo ".NET SDK not found" >&2; exit 1; }
mkdir -p publish
rm -rf publish/DiskCheckTW
"$dotnet_bin" publish src/DiskCheckTW.App -c Release -r win-x64 --self-contained true \
  -p:PublishSingleFile=false -p:PublishReadyToRun=false -o publish/DiskCheckTW
cp README.md README.zh-TW.md LICENSE THIRD_PARTY_NOTICES.md publish/DiskCheckTW/
python3 - <<'PY'
from pathlib import Path

root = Path('publish/DiskCheckTW')
files = sorted(path for path in root.rglob('*') if path.is_file())
dirs = sorted((path for path in root.rglob('*') if path.is_dir()),
              key=lambda path: (-len(path.parts), str(path)))
if not files:
    raise SystemExit('publish/DiskCheckTW has no files')

def nsis_path(path):
    name = str(path.relative_to(root)).replace('/', '\\')
    if any(char in name for char in '\r\n"$'):
        raise SystemExit(f'Unsupported NSIS path: {name!r}')
    return name

lines = ['; Generated by build/publish.sh from publish/DiskCheckTW']
lines += [f'  Delete "$INSTDIR\\{nsis_path(path)}"' for path in files]
lines += [f'  RMDir "$INSTDIR\\{nsis_path(path)}"' for path in dirs]
Path('build/uninstall-files.nsh').write_text('\n'.join(lines) + '\n', encoding='utf-8')
PY
if [[ "${1:-}" == "--publish-only" ]]; then
  exit 0
fi
rm -f publish/DiskCheckTW-0.1.3-win-x64-portable.zip publish/DiskCheckTW-0.1.3-setup.zip
if command -v zip >/dev/null 2>&1; then
  (cd publish && zip -qr DiskCheckTW-0.1.3-win-x64-portable.zip DiskCheckTW)
else
  (cd publish && python3 -m zipfile -c DiskCheckTW-0.1.3-win-x64-portable.zip DiskCheckTW)
fi

if command -v makensis >/dev/null 2>&1; then
  if command -v cygpath >/dev/null 2>&1; then
    payload="$(cygpath -w "$PWD/publish/DiskCheckTW")\*"
    outexe="$(cygpath -w "$PWD/publish/DiskCheckTW-0.1.3-setup.exe")"
  else
    payload="$PWD/publish/DiskCheckTW/*"
    outexe="$PWD/publish/DiskCheckTW-0.1.3-setup.exe"
  fi
  makensis "-DPAYLOAD=$payload" "-DOUTEXE=$outexe" build/installer.nsi
  if command -v zip >/dev/null 2>&1; then
    (cd publish && zip -q DiskCheckTW-0.1.3-setup.zip DiskCheckTW-0.1.3-setup.exe)
  else
    (cd publish && python3 -m zipfile -c DiskCheckTW-0.1.3-setup.zip DiskCheckTW-0.1.3-setup.exe)
  fi
else
  echo "未安裝 NSIS，略過安裝程式"
fi
